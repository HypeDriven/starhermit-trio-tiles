// Writes the native play scripts (tests/native/*.play) from the real rules:
// js/rules/solver.js finds a clearing order for a level, and each pick is the
// keyboard path main.ts takes (focus targets sorted top layer first, then
// reading order; ArrowRight k+1 times reaches target k from no focus, Enter
// picks it). A losing line picks the tile that keeps the tray fullest.
// `node tools/gen-plays.mjs` rewrites the committed scripts; tests/native.mjs
// calls dailyScript() for today's Daily Steep.
import { writeFileSync } from 'node:fs';
import { dirname, join } from 'node:path';
import { fileURLToPath } from 'node:url';
import * as C from '../js/rules/content.js';
import { solve } from '../js/rules/solver.js';
import { legalActions } from '../js/rules/engine.js';
import { Session } from '../js/session/session.js';
import { STRINGS } from '../js/ui/strings.js';

const root = join(dirname(fileURLToPath(import.meta.url)), '..');
function targets(state) {
  const byId = new Map(state.tiles.map((t) => [t.id, t]));
  return legalActions(state).selectable.map((id) => byId.get(id)).sort((a, b) => b.z - a.z || a.gy - b.gy || a.gx - b.gx);
}
/** Key lines that pick `ids` in order (and the final state). */
const NAMES = STRINGS['en-US'].symbols;
/** Key lines that pick `ids` in order (the first `press` of them by a click / touch on the tile's named area on the table). */
export function picks(level, ids, press = 0, verb = 'click') {
  const s = new Session(level);
  const out = [];
  for (const [n, id] of ids.entries()) {
    const list = targets(s.state);
    const k = list.findIndex((t) => t.id === id);
    if (k < 0) throw new Error(`${id} not available`);
    if (n < press) out.push(`${verb} ${NAMES[list[k].sym]} tile, layer ${list[k].z + 1}, ${k + 1} of ${list.length}.`, 'frames 30');
    else {
      for (let i = 0; i <= k; i++) out.push('key ArrowRight 1');
      out.push('key Enter 1', 'frames 2');
    }
    s.submit({ type: 'select', tileId: id });
  }
  return { lines: out, state: s.state };
}
export function winLine(level) {
  const s = new Session(level);
  const r = solve(s.state, { wantPath: true, budget: 2_000_000 });
  if (!r.solvable) throw new Error(`${level.id}: no solution`);
  return r.path;
}
export function loseLine(level) {
  const s = new Session(level);
  const ids = [];
  while (!s.finished) {
    const counts = new Map();
    for (const e of s.state.tray) counts.set(e.sym, (counts.get(e.sym) ?? 0) + 1);
    // a symbol not in the tray (no triple), first by id
    const t = targets(s.state).find((x) => !counts.has(x.sym)) ?? targets(s.state).find((x) => (counts.get(x.sym) ?? 0) < 2) ?? targets(s.state)[0];
    ids.push(t.id);
    s.submit({ type: 'select', tileId: t.id });
  }
  return { ids, state: s.state };
}
export function dailyScript(day = new Date()) {
  const level = C.materializeLevel(C.dailyLevel(C.todayUTC(day)));
  const { lines, state } = picks(level, winLine(level));
  return [
    '# Today\'s Daily Steep (generated at test time: the table follows the UTC date), won by keys.',
    'frames 60', 'click =Daily Steep', 'frames 10', `click Play today`, 'until 900 =Pause', 'frames 10',
    ...lines, 'until 900 Table cleared', 'frames 10', `expect Triples cleared ×${state.score.triples}`, 'save daily-won',
  ].join('\n') + '\n';
}
function write(name, lines) { writeFileSync(join(root, 'tests', 'native', name), lines.join('\n') + '\n'); }

if (process.argv[1] === fileURLToPath(import.meta.url)) {
  // Journey stage 1, desktop: the whole table by keys, results and the next stage
  {
    const level = C.materializeLevel(C.JOURNEY[0]);
    const { lines, state } = picks(level, winLine(level), 3);
    write('journey-desktop.play', [
      '# Journey stage 1 on a desktop window: cleared by the keyboard (generated by tools/gen-plays.mjs).',
      'frames 60', 'click =Play', 'frames 10', 'click Journey', 'frames 10', 'click First Steeps 1', 'until 900 =Pause', 'frames 10', 'save j-start',
      'key KeyH 1', 'frames 30', 'save j-hint',
      ...lines, 'frames 20', 'save j-burst', 'until 900 Table cleared', 'frames 10', 'expect Total', `expect Triples cleared ×${state.score.triples}`, 'save j-results',
      'click Next stage', 'until 900 First Steeps 2', 'frames 30', 'save j-next',
    ]);
  }
  // Lesson 1 on a phone: picked by touching the board mirror's buttons
  {
    const lesson = C.LESSONS[0];
    const level = C.lessonLevel(lesson);
    const ids = winLine(level);
    const s = new Session(level);
    const lines = [];
    for (const id of ids) {
      const avail = legalActions(s.state).selectable;
      const tile = s.state.tiles.find((t) => t.id === id);
      const name = { leaf: 'Tea Leaf', drop: 'Rain Drop', moon: 'Moon', sun: 'Sun', bloom: 'Plum Blossom', wave: 'Wave', crane: 'Crane', lantern: 'Lantern', koi: 'Koi' }[tile.sym];
      lines.push(`touch ${name} tile, available, ${avail.indexOf(id) + 1} of ${avail.length}`, 'frames 20');
      s.submit({ type: 'select', tileId: id });
    }
    write('learn-phone.play', [
      '# viewport 390x844@3',
      '# Lesson 1 on a phone: the board mirror\'s buttons picked by touch (generated by tools/gen-plays.mjs).',
      'frames 60', 'touch =Play', 'frames 10', 'touch Learn', 'frames 10', 'touch Picking Tiles', 'until 900 =Pause', 'frames 10', 'save l-start',
      'touch Board mirror', 'frames 10', 'save l-mirror', ...lines, 'until 900 Table cleared', 'frames 10', `expect ${s.state.score.total}`, 'save l-results',
    ]);
  }
  // A challenge lost on a short landscape phone (the tray fills)
  {
    const level = C.materializeLevel(C.CHALLENGES.find((c) => c.id === 'six-cups'));
    const { ids } = loseLine(level);
    const { lines } = picks(level, ids, 2, 'touch');
    write('challenge-lose-landscape.play', [
      '# viewport 844x390@3',
      '# Six Cups lost on a phone held sideways: the tray fills with no triple (generated by tools/gen-plays.mjs).',
      'frames 60', 'touch =Play', 'frames 10', 'touch Challenge', 'frames 10', 'touch Six Cups', 'until 900 =Pause', 'frames 10', 'save c-start',
      ...lines, 'until 900 Round over', 'frames 10', 'expect The tray filled', 'save c-results',
    ]);
  }
  console.log('wrote tests/native/{journey-desktop,learn-phone,challenge-lose-landscape}.play');
}
